"""Copy an offline SQLite snapshot into an empty PostgreSQL database.

DATABASE_URL supplies the destination secret; never pass it on the command line.
Without --apply this only prints source row counts and makes no destination changes.
"""
import argparse
import os
from pathlib import Path
import sqlite3
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sqlalchemy import create_engine, func, select, text
from app.database import Base, build_engine
from app.models import Call, CallLog, EvalRun

TABLES = [Call.__table__, CallLog.__table__, EvalRun.__table__]


def open_snapshot(path):
    path = Path(path).resolve(strict=True)
    uri = path.as_uri() + '?mode=ro'
    return create_engine('sqlite://', creator=lambda: sqlite3.connect(uri, uri=True))


def copy_records(source, destination):
    """Import atomically; refuse any populated destination rather than overwrite."""
    Base.metadata.create_all(destination)
    with source.connect() as src, destination.begin() as dst:
        if destination.dialect.name == 'postgresql':
            dst.execute(text('LOCK TABLE calls, call_logs, eval_runs IN ACCESS EXCLUSIVE MODE'))
        for table in TABLES:
            if dst.scalar(select(func.count()).select_from(table)):
                raise ValueError('Destination contains records. Migration requires an empty database.')
        counts = {}
        for table in TABLES:
            count = 0
            for batch in src.execute(select(table)).mappings().partitions(500):
                rows = [dict(row) for row in batch]
                dst.execute(table.insert(), rows)
                count += len(rows)
            counts[table.name] = count
            if dst.scalar(select(func.count()).select_from(table)) != count:
                raise ValueError('Migration row-count verification failed.')
        if destination.dialect.name == 'postgresql':
            # Imported log IDs must not collide with IDs generated by future calls.
            dst.execute(text("SELECT setval(pg_get_serial_sequence('call_logs', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM call_logs"))
    return counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, help='Path to an offline SQLite backup')
    parser.add_argument('--apply', action='store_true', help='Copy records into the empty DATABASE_URL destination')
    args = parser.parse_args()
    source = destination = None
    try:
        source = open_snapshot(args.source)
        with source.connect() as connection:
            counts = {table.name: connection.scalar(select(func.count()).select_from(table)) for table in TABLES}
        print('Source counts:', counts)
        if not args.apply:
            print('Dry run only. Stop writes to the source and use --apply to import.')
            return 0
        destination_url = os.environ.get('DATABASE_URL')
        if not destination_url:
            raise ValueError('Set DATABASE_URL securely in the migration environment.')
        destination = build_engine(destination_url)
        if destination.dialect.name != 'postgresql':
            raise ValueError('The migration destination must be PostgreSQL.')
        counts = copy_records(source, destination)
        print('Committed and verified:', counts)
        return 0
    except Exception as error:
        # Connection errors can contain database credentials or transcript values.
        print(f'Migration failed ({type(error).__name__}). Check connectivity, schema, and that the target is empty. No source records were modified.', file=sys.stderr)
        return 1
    finally:
        if source is not None:
            source.dispose()
        if destination is not None:
            destination.dispose()


if __name__ == '__main__':
    raise SystemExit(main())
